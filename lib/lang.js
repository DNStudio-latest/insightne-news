// The reader's language (English, বাংলা, हिन्दी, অসমীয়া, नेपाली). It is kept in a "lang" cookie;
// each page calls initLang() first.
import { cache } from "react";
import { cookies } from "next/headers";
import { validLang, storyText } from "./languages.js";

const store = cache(() => ({ lang: "en" }));

export async function initLang() {
  const value = (await cookies()).get("lang")?.value;
  store().lang = validLang(value);
  return store().lang;
}

export const lang = () => store().lang;

// A story's text in the reader's language if it has been translated, otherwise English.
export function pick(story, field) {
  return storyText(story, field, lang());
}

// True when the reader sees a machine translation (shown as a small note on the story page).
export function isTranslated(story) {
  const code = lang();
  if (code === "en" || story?.kind === "original") return false;
  return code === "bn" ? Boolean(story?.summary_bn?.trim()) : Boolean(story?.translations?.[code]?.summary?.trim());
}

