// Builds public/ai-tools/academic-norms.js: typical stance and metadiscourse rates (per 1,000 words) in human and
// AI-written humanities and social-science abstracts, so the thesis checker can show where a text stands.
//
//   node scripts/thesis-norms.js thesis-corpus.csv [--domain gpab-hss] [--out public/ai-tools/academic-norms.js]
//
// Uses the test split only. Means and medians are both kept; abstracts are denser than thesis chapters, so the
// page presents them as directions, not targets.

import { readFileSync, writeFileSync } from "node:fs";
import { pathToFileURL } from "node:url";
import { loadRows } from "./ai-text-train.js";
import { voiceProfile } from "../public/ai-tools/academic.js";

const median = (xs) => {
  const s = [...xs].sort((a, b) => a - b);
  return s.length ? (s.length % 2 ? s[(s.length - 1) / 2] : (s[s.length / 2 - 1] + s[s.length / 2]) / 2) : 0;
};
const mean = (xs) => (xs.length ? xs.reduce((a, b) => a + b, 0) / xs.length : 0);
const r1 = (v) => Math.round(v * 10) / 10;
const r2 = (v) => Math.round(v * 100) / 100;

export function norms(rows) {
  const out = {};
  for (const label of [0, 1]) {
    const profiles = rows.filter((r) => r.label === label).map((r) => voiceProfile(r.text));
    const keys = Object.keys(profiles[0]?.rates || {});
    const stat = (get, round) => ({ mean: round(mean(profiles.map(get))), median: round(median(profiles.map(get))) });
    out[label ? "ai" : "human"] = {
      n: profiles.length,
      ...Object.fromEntries(keys.map((k) => [k, stat((p) => p.rates[k], r1)])),
      meanSentence: stat((p) => p.meanSentence, r1),
      sentenceVariation: stat((p) => p.sentenceVariation, r2),
    };
  }
  return out;
}

function main() {
  const args = process.argv.slice(2);
  const opt = (flag, fallback) => (args.includes(flag) ? args[args.indexOf(flag) + 1] : fallback);
  const file = args[0];
  if (!file) {
    console.log("Usage: node scripts/thesis-norms.js thesis-corpus.csv [--domain gpab-hss] [--out file.js]");
    process.exit(1);
  }
  const domain = opt("--domain", "gpab-hss");
  const rows = loadRows(readFileSync(file, "utf8")).filter((r) => r.split === "test" && r.domain === domain);
  const result = { source: `${domain} abstracts, test split of the thesis corpus (scripts/thesis-corpus.js)`, ...norms(rows) };
  const out = opt("--out", "public/ai-tools/academic-norms.js");
  writeFileSync(out,
    "// Typical stance and metadiscourse rates per 1,000 words in human and AI-written humanities and social-science\n" +
    "// abstracts (GPABench2). Generated by scripts/thesis-norms.js; do not edit by hand.\n" +
    `export const VOICE_NORMS = ${JSON.stringify(result)};\n`);
  console.log(JSON.stringify(result, null, 1));
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) main();
