// Builds public/ai-tools/academic-words.js: the "style" words whose use in research abstracts jumped after
// ChatGPT was released, with how many times more often they appeared in 2024 than in 2022.
//
// Source: Kobak, González-Márquez, Horvát and Lause (2025), "Delving into LLM-assisted writing in biomedical
// publications through excess vocabulary", Science Advances 11(27), eadt3813. Data and word annotations from
// github.com/berenslab/llm-excess-vocab (MIT licence): results/excess_words.csv (900 excess words, each marked
// "content" or "style") and results/yearly-counts.csv.gz (number of PubMed abstracts containing each word, by year).
//
//   node scripts/thesis-words.js <llm-excess-vocab clone> [--min-ratio 2] [--out public/ai-tools/academic-words.js]

import { readFileSync, writeFileSync } from "node:fs";
import { gunzipSync } from "node:zlib";
import { join } from "node:path";
import { pathToFileURL } from "node:url";
import { parseCsv } from "./ai-text-train.js";

export function excessRatios(wordsCsv, countsCsv, { from = "2022", to = "2024", minRatio = 2 } = {}) {
  const [head, ...rows] = parseCsv(wordsCsv);
  const wi = head.indexOf("word");
  const ti = head.indexOf("type");
  const style = new Set(rows.filter((r) => r[ti] === "style").map((r) => r[wi]));
  const [years, ...counts] = parseCsv(countsCsv);
  const a = years.indexOf(from);
  const b = years.indexOf(to);
  const total = counts[counts.length - 1]; // the last row holds the number of abstracts in each year
  const out = {};
  for (const r of counts.slice(0, -1)) {
    if (!style.has(r[0])) continue;
    const before = Number(r[a]) / Number(total[a]);
    const after = Number(r[b]) / Number(total[b]);
    const ratio = after / Math.max(before, 1e-9);
    if (ratio >= minRatio) out[r[0]] = Math.round(ratio * 10) / 10;
  }
  return Object.fromEntries(Object.entries(out).sort((x, y) => y[1] - x[1]));
}

function main() {
  const args = process.argv.slice(2);
  const dir = args[0];
  const opt = (flag, fallback) => (args.includes(flag) ? args[args.indexOf(flag) + 1] : fallback);
  if (!dir) {
    console.log("Usage: node scripts/thesis-words.js <llm-excess-vocab clone> [--min-ratio 2] [--out file.js]");
    process.exit(1);
  }
  const words = readFileSync(join(dir, "results", "excess_words.csv"), "utf8");
  const counts = gunzipSync(readFileSync(join(dir, "results", "yearly-counts.csv.gz"))).toString("utf8");
  const ratios = excessRatios(words, counts, { minRatio: Number(opt("--min-ratio", 2)) });
  const out = opt("--out", "public/ai-tools/academic-words.js");
  writeFileSync(out,
    "// Style words whose use in research abstracts rose sharply after ChatGPT: how many times more often each appeared\n" +
    "// in 2024 than in 2022 (share of PubMed abstracts). Generated by scripts/thesis-words.js; do not edit by hand.\n" +
    "// Source: Kobak et al. (2025), Science Advances 11(27), eadt3813; data github.com/berenslab/llm-excess-vocab (MIT).\n" +
    `export const EXCESS_WORDS = ${JSON.stringify(ratios)};\n`);
  console.log(`Saved ${Object.keys(ratios).length} words to ${out}`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) main();
